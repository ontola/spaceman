// Renders the app icons for every platform from the logo painter, so they
// follow palette.dart. Run from the repo root:
//
//   flutter test tool/generate_icons.dart
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';
import 'dart:ui' as ui;

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:spaceman/palette.dart';
import 'package:spaceman/widgets/logo.dart';

final _scheme = ColorScheme.fromSeed(seedColor: seedColor);

/// Renders the logo on a [px] wide (and [height] high) canvas, [inset] from
/// the sides and centred vertically unless [top] says otherwise; both are
/// fractions of [px].
Future<Uint8List> _render(
  int px,
  LogoBackground background, {
  double inset = 0,
  double? top,
  int? height,
  LogoLayers layers = LogoLayers.all,
}) async {
  final h = height ?? px;
  final side = px * (1 - 2 * inset);
  final recorder = ui.PictureRecorder();
  final canvas = Canvas(recorder);
  canvas.translate(px * inset, top == null ? (h - side) / 2 : top * px);
  LogoPainter(
    scheme: _scheme,
    background: background,
    layers: layers,
  ).paint(canvas, Size.square(side));
  final image = await recorder.endRecording().toImage(px, h);
  final data = await image.toByteData(format: ui.ImageByteFormat.png);
  return data!.buffer.asUint8List();
}

Future<void> _write(String path, Future<Uint8List> png) async {
  await File(path).writeAsBytes(await png);
  stdout.writeln(path);
}

/// An .ico that holds one PNG per size (Windows Vista and later).
Uint8List _ico(List<(int, Uint8List)> images) {
  final out = BytesBuilder();
  final header = ByteData(6 + 16 * images.length)
    ..setUint16(2, 1, Endian.little)
    ..setUint16(4, images.length, Endian.little);
  var offset = header.lengthInBytes;
  for (final (i, (px, png)) in images.indexed) {
    final e = 6 + 16 * i;
    header
      ..setUint8(e, px >= 256 ? 0 : px)
      ..setUint8(e + 1, px >= 256 ? 0 : px)
      ..setUint16(e + 4, 1, Endian.little)
      ..setUint16(e + 6, 32, Endian.little)
      ..setUint32(e + 8, png.length, Endian.little)
      ..setUint32(e + 12, offset, Endian.little);
    offset += png.length;
  }
  out.add(header.buffer.asUint8List());
  for (final (_, png) in images) {
    out.add(png);
  }
  return out.toBytes();
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test('generate app icons', () async {
    // macOS: rounded square on Apple's grid (824 of 1024, centred).
    const mac = 'macos/Runner/Assets.xcassets/AppIcon.appiconset';
    for (final px in [16, 32, 64, 128, 256, 512, 1024]) {
      await _write(
        '$mac/app_icon_$px.png',
        _render(px, LogoBackground.roundedSquare, inset: 100 / 1024),
      );
    }

    // iOS masks the corners itself and wants no transparency.
    const ios = 'ios/Runner/Assets.xcassets/AppIcon.appiconset';
    final contents = jsonDecode(File('$ios/Contents.json').readAsStringSync());
    for (final img in contents['images'] as List) {
      final pt = double.parse((img['size'] as String).split('x').first);
      final scale = int.parse((img['scale'] as String).replaceAll('x', ''));
      await _write(
        '$ios/${img['filename']}',
        _render((pt * scale).round(), LogoBackground.square),
      );
    }

    // Android: legacy icons, adaptive icon layers (108dp, of which the
    // launcher shows the middle 72dp) and the splash screen colour.
    const android = 'android/app/src/main/res';
    for (final (dir, density) in [
      ('mdpi', 1.0),
      ('hdpi', 1.5),
      ('xhdpi', 2.0),
      ('xxhdpi', 3.0),
      ('xxxhdpi', 4.0),
    ]) {
      await _write(
        '$android/mipmap-$dir/ic_launcher.png',
        _render((48 * density).round(), LogoBackground.circle, inset: 0.04),
      );
      final adaptive = (108 * density).round();
      await _write(
        '$android/mipmap-$dir/ic_launcher_background.png',
        _render(adaptive, LogoBackground.square, layers: LogoLayers.backdrop),
      );
      await _write(
        '$android/mipmap-$dir/ic_launcher_foreground.png',
        _render(
          adaptive,
          LogoBackground.square,
          inset: 0.2,
          top: 0.2,
          layers: LogoLayers.astronaut,
        ),
      );
    }
    final space = LogoPainter.spaceColor(_scheme).toARGB32();
    await File('$android/values/colors.xml').writeAsString(
      '<?xml version="1.0" encoding="utf-8"?>\n'
      '<!-- Generated by tool/generate_icons.dart from lib/palette.dart. -->\n'
      '<resources>\n'
      '    <color name="splash_background">'
      '#${space.toRadixString(16).padLeft(8, '0').toUpperCase()}</color>\n'
      '</resources>\n',
    );
    stdout.writeln('$android/values/colors.xml');

    // iOS launch screen: the astronaut on its own, at 168x185 points.
    const launch = 'ios/Runner/Assets.xcassets/LaunchImage.imageset';
    for (final (suffix, scale) in [('', 1), ('@2x', 2), ('@3x', 3)]) {
      await _write(
        '$launch/LaunchImage$suffix.png',
        _render(168 * scale, LogoBackground.none, height: 185 * scale),
      );
    }

    // Windows.
    final ico = [
      for (final px in [16, 24, 32, 48, 64, 128, 256])
        (px, await _render(px, LogoBackground.circle)),
    ];
    await File('windows/runner/resources/app_icon.ico').writeAsBytes(_ico(ico));
    stdout.writeln('windows/runner/resources/app_icon.ico');

    // A large copy for the README.
    await _write('assets/logo.png', _render(512, LogoBackground.circle));

    // Background of the macOS installer window (tool/make_dmg.sh).
    for (final (suffix, scale) in [('', 1), ('@2x', 2)]) {
      await _write('macos/dmg/background$suffix.png', _dmgBackground(scale));
    }
  });
}

/// The DMG window is [dmgWidth] x [dmgHeight] points with the app and the
/// Applications folder at [dmgAppIcon] and [dmgApplicationsIcon]; keep these
/// in sync with macos/dmg/settings.py.
const dmgWidth = 640, dmgHeight = 400;
const dmgAppIcon = Offset(170, 190), dmgApplicationsIcon = Offset(470, 190);

/// A light window (Finder draws the icon labels in black) with an arrow from
/// the app to Applications and a strip of treemap tiles along the bottom.
Future<Uint8List> _dmgBackground(int scale) async {
  final recorder = ui.PictureRecorder();
  final canvas = Canvas(recorder)..scale(scale.toDouble());
  final size = Size(dmgWidth.toDouble(), dmgHeight.toDouble());
  canvas.drawRect(
    Offset.zero & size,
    Paint()
      ..shader = ui.Gradient.linear(Offset.zero, Offset(0, size.height), [
        _scheme.surface,
        _scheme.surfaceContainer,
      ]),
  );

  // Treemap strip: tiles of shrinking width, like a sorted folder.
  const stripTop = 352.0, gap = 3.0;
  var x = 0.0, width = 150.0;
  for (var i = 0; x < size.width; i++) {
    canvas.drawRRect(
      RRect.fromRectAndRadius(
        Rect.fromLTWH(x + gap / 2, stripTop, width - gap, 60),
        const Radius.circular(4),
      ),
      Paint()..color = tileColor(i, dark: false),
    );
    x += width;
    width = (width * 0.72).clamp(28.0, 150.0);
  }

  // Arrow between the icons, clear of their 128 point frames and labels.
  final arrowPaint = Paint()
    ..color = _scheme.primary
    ..strokeWidth = 6
    ..strokeCap = StrokeCap.round
    ..style = PaintingStyle.stroke;
  final start = Offset(dmgAppIcon.dx + 88, dmgAppIcon.dy - 8);
  final end = Offset(dmgApplicationsIcon.dx - 88, dmgApplicationsIcon.dy - 8);
  canvas.drawLine(start, end, arrowPaint);
  canvas.drawPath(
    Path()
      ..moveTo(end.dx - 18, end.dy - 18)
      ..lineTo(end.dx, end.dy)
      ..lineTo(end.dx - 18, end.dy + 18),
    arrowPaint..strokeJoin = StrokeJoin.round,
  );

  final image = await recorder.endRecording().toImage(
    dmgWidth * scale,
    dmgHeight * scale,
  );
  final data = await image.toByteData(format: ui.ImageByteFormat.png);
  return data!.buffer.asUint8List();
}
